"""Generate ka_sine.h - the sine table the synth oscillators interpolate.

Why a table instead of sinf(): the DLL links with /NODEFAULTLIB (there is no UCRT on
this machine), so the C runtime's math functions are not available at all. A 1024-point
table with linear interpolation is both faster than a polynomial and accurate to about
-80 dB, which is far below anything audible in a preview synth.

Run once; the generated header is committed.  python gen_sine.py
"""

import math
import pathlib

POINTS = 1024
ROWS = 8

here = pathlib.Path(__file__).resolve().parent
values = [math.sin(2.0 * math.pi * i / POINTS) for i in range(POINTS)]
values.append(values[0])  # one guard sample so interpolation never wraps in the inner loop

lines = [
    "/* Generated by gen_sine.py - do not edit by hand. */",
    "#ifndef KA_SINE_H",
    "#define KA_SINE_H",
    "",
    "#define KA_SIN_POINTS %d" % POINTS,
    "",
    "static const float KA_SIN[%d] = {" % len(values),
]

for start in range(0, len(values), ROWS):
    chunk = values[start:start + ROWS]
    lines.append("    " + ", ".join("%.7ff" % v for v in chunk) + ",")

lines += ["};", "", "#endif", ""]

(here / "ka_sine.h").write_text("\n".join(lines), encoding="ascii")
print("wrote", here / "ka_sine.h", len(values), "values")
